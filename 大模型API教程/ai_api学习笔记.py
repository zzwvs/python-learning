API_KEY = "" # dome代码,不放真实apikey
BASS_URL = "https://ws-trgggpccrdp5clut.cn-beijing.mass.aliyuncs.com/compatible-mode/v1"
CHAT_COMPLETION_URL = f"{BASS_URL}/chat/completions"

headers = {
    "Authorization":f"Bearer {API_KEY}", # apikey前面必须有一个空格
    "Content-Type":"application/json"
}
# 对话的上下文管理
messages = [ # 必须是列表
    # 角色  系统提示词    内容
    {"role":"system","content":"你是一个乐于助人的ai助手"},
    #      用户的话
    {"role":"user","content":"你好:请问什么是大模型"},
            # ai之前的话
    {"role":"assistant","content":"大模型是一种基于海量数据训练的大型人工智能模型"},
    {"role":"user","content":"它和不同机器学习有什么区别"}
]
# 请求体
payload = {
    # 指定使用的模型
    "model":"qwen3.8-max",
    # 对话上下文
    "messages":messages,
    # 控制随机性
    "temperature":0.7,
    # 限制最大输出长度
    "max_tokens":512,
    # 是否用流式输出
    "stream":False
}
                            # 请求地址        请求头           请求体       超时时间
response = requests.post(CHAT_COMPLETION_URL,headers=headers,json=payload,timeout=30)

if response.status_code == 200:
    result = response.json() # 解析json数据
    assistant_reply = result["choices"][0]["message"]["content"] # 提取回复并打印
    print(assistant_reply)
else:
    print(f"请求失败:{response.status_code}")



